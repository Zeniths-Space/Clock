#!/usr/bin/env python3
"""Writes the launcher icon layers and the splash icon into res/drawable.

The design, in the Elara 3D style (One UI 8): a clock face that fills the icon, as a white disc lit from
the top left on a pale lavender ground, with four lilac marks at 12, 3, 6 and 9, a deep-ink minute hand,
a glossy brand-purple hour hand and a purple cap. Soft shadows only; no tile.

The hands stay at ten past ten: the icon does not show the time (the owner chose a still icon, 2026-11-09).
Run from the repository root after changing the design: python3 tools/icon.py
"""
import math
import re
from pathlib import Path

RES = Path("app/src/main/res/drawable")
LIGHT, MID, DEEP = "#FFB9A3FF", "#FF7C4DFF", "#FF5527D9"
INK = "#FF2B1766"
LILAC = "#FFB9A2FF"
WHITE = "#FFFFFFFF"
SHADOW = "#262B1766"
CX = CY = 54
FACE_R = 27.5


def circle(cx, cy, r):
    return f"M{cx - r:g},{cy:g}A{r:g},{r:g} 0 1 1 {cx + r:g},{cy:g}A{r:g},{r:g} 0 1 1 {cx - r:g},{cy:g}Z"


def bar(length, width, degrees, start=-2.5):
    """A rounded bar along the radius at `degrees` clockwise from 12, from `start` to `length` out from the centre."""
    a = math.radians(degrees)
    ux, uy = math.sin(a), -math.cos(a)
    px, py = -uy, ux
    w = width / 2
    x0, y0 = CX + ux * start, CY + uy * start
    x1, y1 = CX + ux * length, CY + uy * length
    p = [(x0 + px * w, y0 + py * w), (x1 + px * w, y1 + py * w), (x1 - px * w, y1 - py * w), (x0 - px * w, y0 - py * w)]
    return (f"M{p[0][0]:.2f},{p[0][1]:.2f}L{p[1][0]:.2f},{p[1][1]:.2f}A{w:g},{w:g} 0 0 0 {p[2][0]:.2f},{p[2][1]:.2f}"
            f"L{p[3][0]:.2f},{p[3][1]:.2f}A{w:g},{w:g} 0 0 0 {p[0][0]:.2f},{p[0][1]:.2f}Z")


def lin(x1, y1, x2, y2, *stops):
    items = "".join(f'<item android:offset="{o:g}" android:color="{c}" />' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{x1:g}" '
            f'android:startY="{y1:g}" android:endX="{x2:g}" android:endY="{y2:g}">{items}</gradient></aapt:attr>')


def path(d, fill):
    if fill.startswith("#"):
        return f'        <path android:pathData="{d}" android:fillColor="{fill}" />\n'
    return f'        <path android:pathData="{d}">{fill}</path>\n'


def shadow(d, dx=1.2, dy=2.0):
    return f'    <group android:translateX="{dx:g}" android:translateY="{dy:g}">\n{path(d, SHADOW)}    </group>\n'


def vector(comment, body):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            f"<!-- {comment} Generated by tools/icon.py. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
            f"{body}</vector>\n")


# The hands, each pointing at 12 (degrees 0); `turn` gives the angle they are drawn at.
def hour_hand(turn=0):
    return bar(12.5, 4.6, turn)


def minute_hand(turn=0):
    return bar(20.5, 3.2, turn)


CAP = circle(CX, CY, 3.9)
CAP_DOT = circle(CX, CY, 1.4)
MARKS = "".join(bar(24.0, 2.0, d, start=20.5) for d in (0, 90, 180, 270))


def face():
    disc = circle(CX, CY, FACE_R)
    return (shadow(disc, 0, 1.8)
            + path(disc, lin(CX - FACE_R, CY - FACE_R, CX + FACE_R, CY + FACE_R, (0, WHITE), (0.6, WHITE), (1, "#FFEDE8F6")))
            + path(MARKS, LILAC))


def hour_layer(turn=0, with_shadow=False):
    d = hour_hand(turn)
    body = path(d, lin(CX - 8, CY - 14, CX + 8, CY + 4, (0, LIGHT), (0.5, MID), (1, DEEP)))
    gloss = path(d, lin(CX, CY - 14, CX, CY, (0, "#55FFFFFF"), (1, "#00FFFFFF")))
    return (shadow(d) if with_shadow else "") + body + gloss


def minute_layer(turn=0, with_shadow=False):
    """The minute hand with the cap on top: the cap is round, so it turns with the hand unchanged."""
    d = minute_hand(turn)
    cap = path(CAP, lin(CX - 4, CY - 4, CX + 4, CY + 4, (0, LIGHT), (0.5, MID), (1, DEEP))) + path(CAP_DOT, WHITE)
    return (shadow(d) + shadow(CAP) if with_shadow else "") + path(d, INK) + cap


# Ten past ten: the hour hand a sixth of the way from 10 to 11, the minute hand on the 2.
STATIC_HOUR, STATIC_MINUTE = 305, 60
full = face() + hour_layer(STATIC_HOUR, True) + minute_layer(STATIC_MINUTE, True)

(RES / "ic_launcher_background.xml").write_text(vector(
    "Pale lavender lit from the top left, around the face.",
    path("M0,0H108V108H0z", lin(18, 18, 90, 90, (0, "#FFF4F0FC"), (1, "#FFDCD0FA"))),
))
(RES / "ic_launcher_foreground.xml").write_text(vector("The clock face with its hands at ten past ten.", full))
(RES / "ic_launcher_monochrome.xml").write_text(vector(
    "Themed-icon layer: a ring, the marks and the hands, flat (the system tints it).",
    f'        <path android:pathData="{circle(CX, CY, FACE_R)}{circle(CX, CY, FACE_R - 2.4)}" android:fillColor="{WHITE}" android:fillType="evenOdd" />\n'
    + path(MARKS + hour_hand(STATIC_HOUR) + minute_hand(STATIC_MINUTE) + CAP, WHITE),
))

# The splash icons: the face and hands on nothing (the splash ground is the app's lavender). 288 dp square,
# artwork inside the 192 dp circle Android keeps. splash_icon is still (the window background on Android 8 to
# 11); splash_animated is Android 12+'s animated icon: the face pops in while the minute hand sweeps a full
# turn and the hour hand a sixth of one, both settling at ten past ten. Shadows turn with the hands but stay
# offset down and to the right.
SPLASH_SCALE = 2.6
SPLASH_HEAD = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
               '    xmlns:aapt="http://schemas.android.com/aapt"\n'
               '    android:width="288dp" android:height="288dp" android:viewportWidth="288" android:viewportHeight="288">\n'
               f'    <group android:translateX="{144 - 54 * SPLASH_SCALE:g}" android:translateY="{144 - 54 * SPLASH_SCALE:g}" '
               f'android:scaleX="{SPLASH_SCALE:g}" android:scaleY="{SPLASH_SCALE:g}">\n')

(RES / "splash_icon.xml").write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- Splash icon, still: the clock face, no tile. Generated by tools/icon.py. -->\n"
    + SPLASH_HEAD + f"{full}    </group>\n</vector>\n"
)


def shadowed(layer):
    """The hand's own shapes in the shadow colour (its gradients replaced by a flat fill)."""
    return lambda turn, _: re.sub(r'<path android:pathData="([^"]+)"[^>]*>(?:<aapt:attr.*?</aapt:attr></path>)?', lambda m: f'<path android:pathData="{m.group(1)}" android:fillColor="{SHADOW}" />', layer(turn, False))


def rot(target, start, end, ms, interp):
    return (f'    <target android:name="{target}">\n        <aapt:attr name="android:animation">\n'
            f'            <objectAnimator android:propertyName="rotation" android:valueFrom="{start}" android:valueTo="{end}" '
            f'android:duration="{ms}" android:interpolator="{interp}" />\n        </aapt:attr>\n    </target>\n')


HAND_MS = 700
SWEEP = "@android:interpolator/decelerate_cubic"
pivot = f'android:pivotX="{CX}" android:pivotY="{CY}"'
body = (f'    <group android:name="face" {pivot}>\n{face()}    </group>\n'
        f'    <group android:translateX="1.2" android:translateY="2">\n'
        f'    <group android:name="hour_shadow" {pivot} android:rotation="{STATIC_HOUR}">\n{shadowed(hour_layer)(0, False)}    </group>\n'
        f'    <group android:name="minute_shadow" {pivot} android:rotation="{STATIC_MINUTE}">\n{shadowed(minute_layer)(0, False)}    </group>\n'
        f'    </group>\n'
        f'    <group android:name="hour" {pivot} android:rotation="{STATIC_HOUR}">\n{hour_layer()}    </group>\n'
        f'    <group android:name="minute" {pivot} android:rotation="{STATIC_MINUTE}">\n{minute_layer()}    </group>\n')
pop = ('    <target android:name="face">\n        <aapt:attr name="android:animation">\n            <set>\n'
       + "".join(f'                <objectAnimator android:propertyName="{p}" android:valueFrom="0.6" android:valueTo="1" '
                 f'android:duration="450" android:interpolator="@android:anim/overshoot_interpolator" />\n' for p in ("scaleX", "scaleY"))
       + '            </set>\n        </aapt:attr>\n    </target>\n')
targets = (pop
           + rot("hour", STATIC_HOUR - 60, STATIC_HOUR, HAND_MS, SWEEP) + rot("hour_shadow", STATIC_HOUR - 60, STATIC_HOUR, HAND_MS, SWEEP)
           + rot("minute", STATIC_MINUTE - 360, STATIC_MINUTE, HAND_MS, SWEEP) + rot("minute_shadow", STATIC_MINUTE - 360, STATIC_MINUTE, HAND_MS, SWEEP))
(RES / "splash_animated.xml").write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    f"<!-- Splash icon, animated (Android 12+): the face pops in, the hands sweep to ten past ten in {HAND_MS} ms. Generated by tools/icon.py. -->\n"
    '<animated-vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
    '    xmlns:aapt="http://schemas.android.com/aapt">\n'
    '    <aapt:attr name="android:drawable">\n'
    + SPLASH_HEAD.replace('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:aapt="http://schemas.android.com/aapt"\n', '<vector\n')
    + body + "    </group>\n</vector>\n    </aapt:attr>\n" + targets + "</animated-vector>\n"
)
